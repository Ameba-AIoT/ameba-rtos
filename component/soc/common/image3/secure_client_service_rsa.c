/*
 * secure_client_service_rsa.c -- RSA-2048 client key service (Secure World)
 *
 * Security property:
 *   The BadSSL Client RSA-2048 private key is stored as raw parameter arrays
 *   in this file (image3, Secure World only).  On first call the parameters
 *   are imported directly into an mbedtls_rsa_context via
 *   mbedtls_rsa_import_raw() + mbedtls_rsa_complete(), bypassing the generic
 *   mbedtls_pk_parse_key() path.
 *
 *   This avoids pulling pkparse.o -> x509_crt.o -> ssl_tls.o -> ssl_msg.o
 *   (the +61 KB dependency chain), allowing img3 to fit in TZ_S_SIZE = 64 KB.
 *
 * NS side receives only:
 *   - Certificate PEM (public, safe to share)
 *   - RSA signatures produced by secure_client_sign()
 */

